import json
import re
from typing import Any, Optional

from ..config import settings
from .recommendations import demo_home, demo_party, demo_jewelry, marketplace_link

try:
    from google import genai
    from google.genai import types
except ImportError:
    genai = None
    types = None


_client = None


def get_client():
    global _client

    if not settings.gemini_api_key or genai is None:
        return None

    if _client is None:
        _client = genai.Client(
            api_key=settings.gemini_api_key
        )

    return _client


def _prompt(planner: str, data: dict) -> str:
    return f"""
You are PocketSmart AI, a budget-aware recommendation assistant.

Planner: {planner}

User information:
{json.dumps(data, ensure_ascii=False)}

Create a practical plan that stays within the stated total budget.

Use Indian Rupees (₹).

IMPORTANT:
- Return ONLY valid JSON.
- Do not use Markdown.
- Do not wrap the JSON in ```json.
- Do not add explanations before or after the JSON.
- Estimated prices only; never claim live prices.
- Do not claim live stock availability.
- Do not claim real-time marketplace API data.
- Marketplace links will be generated by the application.

Return exactly this structure:

{{
    "planner": "{planner}",
    "budget": {data.get("budget", 0)},
    "summary": "Short useful summary",
    "allocations": {{
        "category": 0
    }},
    "recommendations": [
        {{
            "category": "Furniture",
            "title": "Product name",
            "platform": "Amazon",
            "estimated_price": 0,
            "reason": "Why this is recommended",
            "link": ""
        }}
    ],
    "tips": [
        "Useful budget tip"
    ]
}}

Give 4 to 8 recommendations.

Make sure the total estimated recommendation spending stays within the user's budget.

Be practical and concise.
"""


def _extract_json(text: str) -> dict[str, Any]:
    """
    Extract a JSON object safely from Gemini output.
    """

    if not text:
        raise ValueError("Gemini returned an empty response.")

    text = text.strip()

    # Remove markdown fences if Gemini still returns them.
    text = re.sub(
        r"^```(?:json)?\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r"\s*```$",
        "",
        text
    )

    text = text.strip()

    # First try the complete response.
    try:
        result = json.loads(text)

        if isinstance(result, dict):
            return result

    except json.JSONDecodeError:
        pass

    # Find the JSON object inside surrounding text.
    start = text.find("{")
    end = text.rfind("}")

    if start == -1 or end == -1 or end <= start:
        raise ValueError(
            "Gemini did not return a JSON object."
        )

    candidate = text[start:end + 1]

    try:
        result = json.loads(candidate)

        if isinstance(result, dict):
            return result

    except json.JSONDecodeError as exc:
        raise ValueError(
            f"Invalid JSON returned by Gemini: {exc}"
        ) from exc

    raise ValueError("Gemini returned an invalid JSON structure.")


def _response_text(response: Any) -> str:
    """
    Safely extract all textual parts from a Gemini response.

    This handles newer google-genai responses where response.text
    may not contain the complete result.
    """

    # Try response.text first.
    try:
        text = response.text

        if text:
            return str(text).strip()

    except Exception:
        pass

    # Collect text from all candidates/content parts.
    chunks = []

    try:
        candidates = getattr(
            response,
            "candidates",
            None
        ) or []

        for candidate in candidates:

            content = getattr(
                candidate,
                "content",
                None
            )

            if not content:
                continue

            parts = getattr(
                content,
                "parts",
                None
            ) or []

            for part in parts:

                value = getattr(
                    part,
                    "text",
                    None
                )

                if value:
                    chunks.append(str(value))

    except Exception:
        pass

    return "\n".join(chunks).strip()


def _normalize(
    result: dict,
    planner: str,
    data: dict
) -> dict:

    result.setdefault(
        "planner",
        planner
    )

    result.setdefault(
        "budget",
        data.get("budget", 0)
    )

    result.setdefault(
        "summary",
        "Your personalized PocketSmart AI plan."
    )

    result.setdefault(
        "allocations",
        {}
    )

    result.setdefault(
        "recommendations",
        []
    )

    result.setdefault(
        "tips",
        []
    )

    result["demo_mode"] = False

    # Ensure recommendations are valid.
    for item in result["recommendations"]:

        item.setdefault(
            "category",
            "General"
        )

        item.setdefault(
            "title",
            "Recommended item"
        )

        item.setdefault(
            "platform",
            "Amazon"
        )

        item.setdefault(
            "reason",
            "Suitable for your requirements."
        )

        try:
            item["estimated_price"] = float(
                item.get(
                    "estimated_price",
                    0
                ) or 0
            )

        except (ValueError, TypeError):
            item["estimated_price"] = 0

        # Generate safe marketplace search link.
        item["link"] = marketplace_link(
            item.get("platform", "Amazon"),
            item.get("title", "product")
        )

    return result


def _fallback(planner: str, data: dict, error=None):

    demo_functions = {
        "home": demo_home,
        "party": demo_party,
        "jewelry": demo_jewelry
    }

    result = demo_functions[planner](data)

    result["demo_mode"] = True

    if error:
        result["summary"] = (
            "Gemini was unavailable, so a safe fallback "
            "plan was used. Details: "
            f"{type(error).__name__}."
        )

    return result


def generate_text(
    planner: str,
    data: dict
):
    """
    Generate a plan using Gemini.

    This function is required by planner_routes.py.
    """

    client = get_client()

    # No API key → demo mode.
    if client is None:
        return _fallback(
            planner,
            data
        )

    try:

        prompt = _prompt(
            planner,
            data
        )

        config = types.GenerateContentConfig(
            temperature=0.2,
            max_output_tokens=2500,
            response_mime_type="application/json"
        )

        response = client.models.generate_content(
            model=settings.gemini_model,
            contents=prompt,
            config=config
        )

        raw_text = _response_text(
            response
        )

        result = _extract_json(
            raw_text
        )

        return _normalize(
            result,
            planner,
            data
        )

    except Exception as exc:

        # Never crash the API because Gemini failed.
        return _fallback(
            planner,
            data,
            exc
        )


def generate_jewelry(
    data: dict,
    image_bytes: Optional[bytes] = None,
    mime_type: Optional[str] = None
):
    """
    Generate jewelry recommendations.

    Supports:
    - text-only jewelry planning
    - image + text multimodal planning
    """

    client = get_client()

    # No Gemini or no image → normal text planner.
    if client is None:

        return _fallback(
            "jewelry",
            data
        )

    try:

        prompt = _prompt(
            "jewelry",
            data
        )

        contents = []

        # Add outfit image when provided.
        if (
            image_bytes
            and types is not None
        ):

            image_part = types.Part.from_bytes(
                data=image_bytes,
                mime_type=mime_type or "image/jpeg"
            )

            contents.append(
                image_part
            )

        contents.append(
            prompt
        )

        config = types.GenerateContentConfig(
            temperature=0.2,
            max_output_tokens=2500,
            response_mime_type="application/json"
        )

        response = client.models.generate_content(
            model=settings.gemini_model,
            contents=contents,
            config=config
        )

        raw_text = _response_text(
            response
        )

        result = _extract_json(
            raw_text
        )

        return _normalize(
            result,
            "jewelry",
            data
        )

    except Exception as exc:

        return _fallback(
            "jewelry",
            data,
            exc
        )